def cosine_sim_frames(inp_vid,opt_frms):
    missing_frames_lst = []
    cap = cv.VideoCapture(inp_vid)
    cnt = 0
    res, frame = cap.read()
    opt_frm = os.path.join(opt_frms, 'frame')
    opt_pth = opt_frm + str(cnt) + '.jpg'

    prev = frame
    prev_gray = cv.cvtColor(prev,cv.COLOR_BGR2GRAY)
    # cv.imwrite(opt_pth, prev)
    res, frame = cap.read()
    while res:
        cnt += 1
        curr = frame
        curr_gray = cv.cvtColor(curr, cv.COLOR_BGR2GRAY)
        sim_score = ssim(prev_gray, curr_gray)
        if sim_score<0.7:
            prev = curr.copy()
            prev_gray = curr_gray.copy()
            # opt_pth = opt_frm + str(cnt) + '.jpg'
            # cv.imwrite(opt_pth,prev)
        else:
            frm_score = f'frame{cnt} .jpg:{sim_score}'
            missing_frames_lst.append(frm_score)
        res, frame = cap.read()
    cap.release()
    return cnt - len(missing_frames_lst)- 1, missing_frames_lst


def optc_flw_frames(inp_vid,opt_frms):
    missing_frames = []
    lk_params = dict(winSize=(50, 50),
                     maxLevel=2,
                     criteria=(cv.TERM_CRITERIA_EPS | cv.TERM_CRITERIA_COUNT, 10, 0.03))
    cap = cv.VideoCapture(inp_vid)
    cnt = 0
    ret, frame = cap.read()
