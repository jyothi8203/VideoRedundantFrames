@njit(fastmath=True)
def ssim_lite(x, y):
    mu_x = x.mean()
    mu_y = y.mean()
    #variance for adjacent frames x and y are calculated
    #co-variance for x and y is calculated
    var_x = ((x - mu_x) ** 2).mean()
    var_y = ((y - mu_y) ** 2).mean()
    cov_xy = ((x - mu_x) * (y - mu_y)).mean()
# from actual SSIM K1 = 0.01, K2 = 0.03, default sigma for Gaussian is 1.5,
    #C1, C2 are two constants with C1 = 650.25, C2 = 1950.75
    C1 = 0.01 * 255 * 255
    C2 = 0.03 * 255 * 255
    # similarity is calculated
    numer = ((2 * mu_x * mu_y + C1) * (2 * cov_xy + C2))
    denom = ((mu_x**2 + mu_y**2 + C1) * (var_x + var_y + C2))
    return  numer/ denom


@njit(parallel=True, fastmath=True)
# @njit(parallel=True, fastmath=True)
def ssim_numba(img1, img2):
    C1 = 6.5025
    C2 = 58.5225

    mu1 = np.mean(img1)
    mu2 = np.mean(img2)

    sigma1 = np.var(img1)
    sigma2 = np.var(img2)
    sigma12 = np.mean((img1 - mu1) * (img2 - mu2))

    numerator = (2*mu1*mu2 + C1) * (2*sigma12 + C2)
    denominator = (mu1**2 + mu2**2 + C1) * (sigma1 + sigma2 + C2)

    return numerator / denominator


